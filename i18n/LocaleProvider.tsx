interface LocaleContextValue {
  locale: AppLocale;
  isRtl: boolean;
  t: (key: string, values?: Record<string, string | number>) => string;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

/** Traduction utilisable aussi par les moteurs métier hors composants React. */
export const translateLocaleMessage = (
  locale: AppLocale,
  key: string,
  values: Record<string, string | number> = {},
): string => {
  const template = messages[locale][key] ?? messages.fr[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, token) => String(values[token] ?? `{${token}}`));
};

interface LocaleProviderProps {
  locale: AppLocale;
  children: React.ReactNode;
}

export const LocaleProvider: React.FC<LocaleProviderProps> = ({ locale, children }) => {
  const isRtl = locale === 'ar';

  useEffect(() => {
    const root = document.documentElement;
    root.lang = locale;
    root.dir = isRtl ? 'rtl' : 'ltr';
    root.classList.toggle('font-ar', isRtl);
  }, [isRtl, locale]);

  const value = useMemo<LocaleContextValue>(() => ({
    locale,
    isRtl,
    t: (key, values = {}) => translateLocaleMessage(locale, key, values),
  }), [isRtl, locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
};

export const useLocale = (): LocaleContextValue => {
  const context = useContext(LocaleContext);
  if (!context) throw new Error('useLocale must be used within LocaleProvider');
  return context;
};

import { produce } from 'immer';
import type { AppConfig, AppLocale, LessonsData, ManualAssessment } from '../../types';
import { buildLessonRows, type LessonRow } from '../notebook/lessonRows';
import { findItem } from '../notebook/dataUtils';
import { parseTrailingNumber } from './assessmentSync';
import { extractDateRange, placeBlockChronologically, syncAssessmentDateToNotebook } from './notebookSyncBridge';
import { normalizeDigits } from './homeworkNumbering';

export const correctionBlockId = (id: string) => `homework-correction:${id}`;

/** Stable identity first; ambiguous historical corrections are never guessed. */
export function correctionOwner(row: LessonRow, manual: readonly ManualAssessment[]): ManualAssessment | undefined {
  if (row.elementType !== 'correction_devoir_maison') return undefined;
  const exact = manual.find(item => item.type === 'maison' && row.data._tempId === correctionBlockId(item.id));
  if (exact) return exact;
  const num = parseTrailingNumber('title' in row.data ? row.data.title : undefined);
  const date = extractDateRange(row.data.date).startDate;
  const candidates = manual.filter(item => item.type === 'maison' && item.num === num && !!date && item.correctionDateISO === date);
  return candidates.length === 1 ? candidates[0] : undefined;
}

export function syncHomeworkCorrectionContent(lessons: LessonsData, homework: Pick<ManualAssessment, 'id' | 'num' | 'correctionDateISO'>,
  locale: AppLocale, previousDate = homework.correctionDateISO): LessonsData {
  const rows = buildLessonRows(lessons);
  const id = correctionBlockId(homework.id);
  const exact = rows.find(row => row.data._tempId === id);
  const legacy = rows.filter(row => row.elementType === 'correction_devoir_maison'
    && !row.data._tempId?.startsWith('homework-correction:')
    && parseTrailingNumber('title' in row.data ? row.data.title : undefined) === homework.num
    && !!previousDate && extractDateRange(row.data.date).startDate === previousDate);
  const target = exact ?? (legacy.length === 1 ? legacy[0] : undefined);
  if (target) {
    return produce(lessons, draft => {
      const { item } = findItem(draft, target.indices);
      if (item) { item.date = homework.correctionDateISO || undefined; item._tempId = id; }
    });
  }
  if (!homework.correctionDateISO || legacy.length > 1) return lessons;
  const label = locale === 'ar' ? 'تصحيح الفرض المنزلي' : locale === 'en' ? 'Homework correction' : 'Correction du devoir maison';
  return placeBlockChronologically(lessons, { type: 'correction_devoir_maison', title: `${label} ${homework.num}`,
    date: homework.correctionDateISO, _tempId: id }).lessons;
}

/** Upgrade existing dated records into real content, preserving documents and students. */
export function materializeContentAssessments(lessons: LessonsData, config: Partial<AppConfig>, classId: string, locale: AppLocale): LessonsData {
  let result = lessons;
  const removed = new Set(config.removedAssessments?.[classId] ?? []);
  for (const item of config.manualAssessments?.[classId] ?? []) {
    if (removed.has(item.id) || removed.has(item.id.split(':').at(-1)!)) continue;
    // An established content date wins over a stale copy in settings.
    const existing = buildLessonRows(result);
    if (item.type === 'maison' && item.correctionDateISO && !existing.some(row => row.data._tempId === correctionBlockId(item.id))) {
      result = syncHomeworkCorrectionContent(result, item, locale);
    }
    if (item.type === 'colle') {
      if (existing.some(row => row.elementType === 'colle' && (row.data._tempId === `dev-block-${item.id}`
        || parseTrailingNumber('title' in row.data ? row.data.title : undefined) === item.num))) continue;
      result = syncAssessmentDateToNotebook(result, { ...item,
        dateISO: config.assessmentDates?.[classId]?.[item.id] ?? item.dateISO }, locale).lessons;
    }
  }
  // Remove only exact labels generated by the former remark chip, after a
  // real correction block exists. Free teacher notes remain untouched.
  const corrections = buildLessonRows(result).filter(row => row.elementType === 'correction_devoir_maison');
  const owners = corrections.map(row => correctionOwner(row, config.manualAssessments?.[classId] ?? [])).filter(Boolean);
  return produce(result, draft => {
    for (const row of buildLessonRows(result)) {
      const remark = row.data.remark;
      if (!remark) continue;
      const date = extractDateRange(row.data.date).startDate;
      const nums = new Set(owners.filter(owner => owner?.correctionDateISO === date).map(owner => owner!.num));
      if (!nums.size) continue;
      const kept = remark.split('\n').filter(line => {
        const match = normalizeDigits(line.trim()).match(/^(?:Correction du devoir (?:à la )?maison (\d+)|Homework (\d+) correction|تصحيح الفرض المنزلي رقم (\d+))$/i);
        return !match || !nums.has(Number(match[1] ?? match[2] ?? match[3]));
      }).join('\n').trim();
      if (kept === remark) continue;
      const { item } = findItem(draft, row.indices);
      if (item) { if (kept) item.remark = kept; else delete item.remark; }
    }
  });
}
